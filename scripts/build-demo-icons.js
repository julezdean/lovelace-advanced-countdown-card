// Writes demo/icons.js: the handful of Material Design Icons the demo uses,
// as SVG paths. Home Assistant ships these inside its frontend; outside it
// the demo's <ha-icon> stand-in needs them from somewhere.
//
//   node scripts/build-demo-icons.js
import { writeFileSync } from "node:fs";
import * as mdi from "@mdi/js";

const NAMES = [
  "coffee",
  "timer-outline",
  "timer-sand",
  "washing-machine",
  "battery-80",
  "calendar-clock",
  "alert-circle-outline",
  "rocket-launch-outline",
  "dishwasher",
  "pizza",
  "tea",
  "alarm",
  "car-electric",
  "stove",
  "counter",
];

const camel = (name) =>
  "mdi" + name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

const icons = {};
for (const name of NAMES) {
  const path = mdi[camel(name)];
  if (!path) throw new Error(`No icon mdi:${name}`);
  icons[`mdi:${name}`] = path;
}
writeFileSync(
  new URL("../demo/icons.js", import.meta.url),
  "// Generated by scripts/build-demo-icons.js from @mdi/js -- do not edit.\n" +
    `export const ICONS = ${JSON.stringify(icons, null, 2)};\n`,
);
console.log(`demo/icons.js: ${NAMES.length} icons`);
